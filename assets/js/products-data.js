/**
 * Look up a product by its stable product id (e.g. "iphone13pro").
 * @param {string} id
 * @returns {object|null}
 */
function cheynFindProduct(id) {
  if (!id) return null;
  return CHEYN_PRODUCTS.find(function(p) { return p.id === id; }) || null;
}
